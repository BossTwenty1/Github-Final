create or replace function public.audit_safe_row(p_table_name text, p_row jsonb)
returns jsonb
language sql
immutable
set search_path = pg_catalog, public, pg_temp
as $$
    select case p_table_name
        when 'lot_owner' then p_row - array[
            'first_name', 'middle_name', 'last_name', 'suffix', 'aliases',
            'address', 'representative_name', 'representative_contact',
            'representative_relation'
        ]
        when 'deceased' then p_row - 'cause_of_death'
        when 'burial_record' then p_row - array['service_provider', 'quality_notes']
        when 'account' then p_row - 'username'
        else p_row
    end;
$$;

revoke all on function public.audit_safe_row(text, jsonb) from public;

create or replace function public.write_audit_event()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    old_row jsonb;
    new_row jsonb;
    row_key text;
    event_action text;
    actor_id uuid;
begin
    if tg_op = 'DELETE' then
        old_row := to_jsonb(old);
    else
        new_row := to_jsonb(new);
    end if;

    row_key := case tg_table_name
        when 'site' then 'site_id'
        when 'area' then 'area_id'
        when 'sector' then 'sector_id'
        when 'block' then 'block_id'
        when 'lot_owner' then 'lot_owner_id'
        when 'lot' then 'lot_id'
        when 'deceased' then 'deceased_id'
        when 'role' then 'role_id'
        when 'account' then 'account_id'
        when 'burial_record' then 'burial_id'
        when 'photo' then 'photo_id'
        when 'map_node' then 'node_id'
        when 'map_edge' then 'edge_id'
        else null
    end;

    if tg_op = 'INSERT' then
        event_action := 'insert';
    elsif tg_op = 'DELETE' then
        event_action := 'delete';
    elsif tg_table_name = 'lot' and (
        (old_row ->> 'coordinate_status') is distinct from (new_row ->> 'coordinate_status')
        or (old_row ->> 'coordinate_verified') is distinct from (new_row ->> 'coordinate_verified')
    ) then
        event_action := 'verify';
    elsif tg_table_name in ('deceased', 'photo', 'lot') and (
        ((old_row ->> 'public_display') is distinct from (new_row ->> 'public_display')
            and new_row ->> 'public_display' = 'true')
        or ((old_row ->> 'approval_status') is distinct from (new_row ->> 'approval_status')
            and new_row ->> 'approval_status' = 'approved')
    ) then
        event_action := 'approve';
    elsif (
        tg_table_name = 'lot' and (old_row ->> 'status') is distinct from (new_row ->> 'status')
        or tg_table_name = 'burial_record' and (
            (old_row ->> 'record_status') is distinct from (new_row ->> 'record_status')
            or (old_row ->> 'interment_status') is distinct from (new_row ->> 'interment_status')
        )
        or tg_table_name = 'photo' and (old_row ->> 'approval_status') is distinct from (new_row ->> 'approval_status')
    ) then
        event_action := 'status_change';
    else
        event_action := 'update';
    end if;

    select a.account_id
      into actor_id
      from public.account as a
     where a.account_id = auth.uid();

    insert into public.audit_log (
        actor_account_id,
        action,
        table_name,
        record_id,
        old_values,
        new_values
    ) values (
        actor_id,
        event_action,
        tg_table_name,
        coalesce(new_row ->> row_key, old_row ->> row_key),
        public.audit_safe_row(tg_table_name, old_row),
        public.audit_safe_row(tg_table_name, new_row)
    );

    if tg_op = 'DELETE' then
        return old;
    end if;
    return new;
end;
$$;

revoke all on function public.write_audit_event() from public;

