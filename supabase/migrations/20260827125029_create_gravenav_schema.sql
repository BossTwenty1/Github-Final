        raise exception 'Only approved pending accounts may be activated';
    end if;

    return activated_account;
end;
$$;

create or replace function public.admin_deactivate_account(
    p_account_id uuid,
    p_account_status text
)
returns public.account
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    deactivated_account public.account;
begin
    if not public.is_active_admin() then
        raise exception 'Only an active ADMIN may deactivate accounts';
    end if;

    if p_account_id = auth.uid() then
        raise exception 'An ADMIN may not deactivate their own account';
    end if;

    if upper(p_account_status) not in ('SUSPENDED', 'REVOKED') then
        raise exception 'Deactivation status must be SUSPENDED or REVOKED';
    end if;

    if exists (
        select 1
        from public.account as target
        join public.role as target_role on target_role.role_id = target.role_id
        where target.account_id = p_account_id
          and upper(target_role.role_name) = 'ADMIN'
          and (
              select count(*)
              from public.account as active_admin
              join public.role as active_admin_role on active_admin_role.role_id = active_admin.role_id
              where active_admin.account_status = 'ACTIVE'
                and active_admin.is_active
                and upper(active_admin_role.role_name) = 'ADMIN'
          ) <= 1
    ) then
        raise exception 'The last active ADMIN may not be deactivated';
    end if;

    update public.account
       set is_active = false,
           account_status = upper(p_account_status),
           deactivated_at = current_timestamp
     where account_id = p_account_id
       and account_status = 'ACTIVE'
    returning * into deactivated_account;

    if not found then
        raise exception 'Only active accounts may be deactivated';
    end if;

    return deactivated_account;
end;
$$;

create or replace function public.admin_change_account_role(
    p_account_id uuid,
    p_role_name text
)
returns public.account
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    target_role_id bigint;
    changed_account public.account;
begin
    if not public.is_active_admin() then
        raise exception 'Only an active ADMIN may change account roles';
    end if;

    select r.role_id
      into target_role_id
      from public.role as r
     where upper(r.role_name) = upper(p_role_name)
       and upper(r.role_name) in ('ADMIN', 'MANAGER');

    if target_role_id is null then
        raise exception 'Only ADMIN and MANAGER roles may be assigned';
    end if;

    if exists (
        select 1
        from public.account as target
        join public.role as target_role on target_role.role_id = target.role_id
        where target.account_id = p_account_id
          and upper(target_role.role_name) = 'ADMIN'
          and target_role_id <> target.role_id
          and (
              select count(*)
              from public.account as active_admin
              join public.role as active_admin_role on active_admin_role.role_id = active_admin.role_id
              where active_admin.account_status = 'ACTIVE'
                and active_admin.is_active
                and upper(active_admin_role.role_name) = 'ADMIN'
          ) <= 1
    ) then
        raise exception 'The last active ADMIN may not be demoted';
    end if;

    update public.account
       set role_id = target_role_id
     where account_id = p_account_id
       and account_status <> 'REVOKED'
    returning * into changed_account;

    if not found then
        raise exception 'The target account does not exist or is revoked';
    end if;

    return changed_account;
end;
$$;

create or replace function public.export_audit_log(
    p_from timestamptz default null,
    p_to timestamptz default null
)
returns setof public.audit_log
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    actor_id uuid;
begin
    if not public.is_active_admin_or_manager() then
        raise exception 'Only active ADMIN or MANAGER accounts may export audit logs';
    end if;

    select a.account_id
      into actor_id
      from public.account as a
     where a.account_id = auth.uid();

    insert into public.audit_log (
        actor_account_id,
        action,
        table_name,
        record_id,
        old_values,
        new_values
    ) values (
        actor_id,
        'export',
        'audit_log',
        'export',
        null,
        null
    );

    return query
    select al.*
      from public.audit_log as al
     where (p_from is null or al.created_at >= p_from)
       and (p_to is null or al.created_at < p_to)
     order by al.created_at, al.audit_id;
end;
$$;

