create or replace view public.public_burial_records
with (security_barrier = true)
as
select
    br.burial_id,
    d.display_name,
    d.birth_date,
    d.death_date,
    br.record_status,
    l.lot_code,
    l.location_geom,
    l.px_loc_x,
    l.px_loc_y,
    l.coordinate_verified as location_verified
from public.burial_record as br
join public.deceased as d on d.deceased_id = br.deceased_id
join public.lot as l on l.lot_id = br.lot_id
where br.record_status = 'active'
  and d.public_display;

create or replace view public.public_burial_photos
with (security_barrier = true)
as
select
    p.photo_id,
    p.burial_id,
    p.storage_path,
    p.file_name,
    p.caption,
    p.captured_at
from public.photo as p
join public.burial_record as br on br.burial_id = p.burial_id
join public.deceased as d on d.deceased_id = br.deceased_id
where p.approval_status = 'approved'
  and p.public_display
  and br.record_status = 'active'
  and d.public_display;

