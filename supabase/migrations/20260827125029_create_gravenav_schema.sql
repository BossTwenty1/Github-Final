-- GraveNav initial schema migration.
--
-- This migration is intentionally local-first and contains no seed data. GPS and
-- image-map coordinates remain nullable until they are collected. Verification
-- describes data quality and is not a public visibility gate.

create schema if not exists extensions;
create extension if not exists postgis with schema extensions;

set search_path = public, extensions;

create table public.site (
    site_id bigint generated by default as identity primary key,
    site_name text not null,
    address text not null,
    boundary_geom extensions.geography(Polygon, 4326),
    geo_transform_json jsonb,
    created_at timestamptz not null default current_timestamp,
    updated_at timestamptz not null default current_timestamp
);

create table public.area (
    area_id bigint generated by default as identity primary key,
    site_id bigint not null references public.site(site_id) on delete restrict,
    area_code varchar(100) not null,
    area_name text not null,
    area_category text not null,
    boundary_geom extensions.geography(Polygon, 4326),
    constraint area_site_code_key unique (site_id, area_code)
