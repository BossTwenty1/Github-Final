-- Account provisioning is intentionally function-only. Auth users must be
-- created or invited by a protected server-side Auth Admin operation first;
-- these functions only manage the corresponding public.account row.
create or replace function public.bootstrap_first_admin(
    p_account_id uuid,
    p_username text
)
returns public.account
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    admin_role_id bigint;
    new_account public.account;
begin
    select r.role_id
      into admin_role_id
      from public.role as r
     where upper(r.role_name) = 'ADMIN';

    if admin_role_id is null then
        raise exception 'ADMIN role is not configured';
    end if;

    if exists (
        select 1
        from public.account as a
        where a.role_id = admin_role_id
          and a.account_status = 'ACTIVE'
          and a.is_active
    ) then
        raise exception 'The first ADMIN has already been provisioned';
    end if;

    if not exists (select 1 from auth.users where id = p_account_id) then
        raise exception 'The Auth user must exist before account provisioning';
    end if;

    if p_username is null or btrim(p_username) = '' then
        raise exception 'A username is required';
    end if;

    insert into public.account (
        account_id,
        role_id,
        username,
        is_active,
        account_status,
        created_by,
        approved_by,
        approved_at
    ) values (
        p_account_id,
        admin_role_id,
        btrim(p_username),
        true,
        'ACTIVE',
        null,
        null,
        current_timestamp
    )
    returning * into new_account;

    return new_account;
end;
$$;

create or replace function public.admin_create_account(
    p_account_id uuid,
    p_username text,
    p_role_name text
)
returns public.account
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    target_role_id bigint;
    new_account public.account;
begin
    if not public.is_active_admin() then
        raise exception 'Only an active ADMIN may create accounts';
    end if;

    if not exists (select 1 from auth.users where id = p_account_id) then
        raise exception 'The Auth user must exist before account provisioning';
    end if;

    if p_username is null or btrim(p_username) = '' then
        raise exception 'A username is required';
    end if;

    select r.role_id
      into target_role_id
      from public.role as r
     where upper(r.role_name) = upper(p_role_name)
       and upper(r.role_name) in ('ADMIN', 'MANAGER');

    if target_role_id is null then
        raise exception 'Only ADMIN and MANAGER accounts may be provisioned';
    end if;

    insert into public.account (
        account_id,
        role_id,
        username,
        is_active,
        account_status,
        created_by
    ) values (
        p_account_id,
        target_role_id,
        btrim(p_username),
        false,
        'PENDING',
        auth.uid()
    )
    returning * into new_account;

    return new_account;
end;
$$;

create or replace function public.admin_approve_account(p_account_id uuid)
returns public.account
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    approved_account public.account;
begin
    if not public.is_active_admin() then
        raise exception 'Only an active ADMIN may approve accounts';
    end if;

    update public.account
       set approved_by = auth.uid(),
           approved_at = current_timestamp
     where account_id = p_account_id
       and account_status = 'PENDING'
       and approved_at is null
    returning * into approved_account;

    if not found then
        raise exception 'Only pending, unapproved accounts may be approved';
    end if;

    return approved_account;
end;
$$;

create or replace function public.admin_activate_account(p_account_id uuid)
returns public.account
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    activated_account public.account;
begin
    if not public.is_active_admin() then
        raise exception 'Only an active ADMIN may activate accounts';
    end if;

    update public.account
       set is_active = true,
           account_status = 'ACTIVE',
           deactivated_at = null
     where account_id = p_account_id
       and account_status = 'PENDING'
